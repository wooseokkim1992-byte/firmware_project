#ifndef VIBRATION_H
#define VIBRATION_H

#include <stdint.h>
#include <stdbool.h>


/*
 * ============================================================
 * Vibration Data Processing
 * ============================================================
 *
 * 담당 기능 : 중분류 1.2 진동 데이터 처리
 *
 * MPU6050에서 읽은 가속도 X/Y/Z 값을 이용하여
 * 실제 "진동 성분"을 추출하고 RMS / Peak 등을 계산한다.
 *
 *
 * 전체 처리 흐름
 *
 * MPU6050 accel_x / accel_y / accel_z
 *
 *              ↓
 *
 * 중력 + 고정 Offset 기준값 추적
 *
 *              ↓
 *
 * 기준값 제거
 *
 *              ↓
 *
 * 실제 움직임 / 진동 성분
 *
 *              ↓
 *
 * 소프트웨어 노이즈 필터
 *
 *              ↓
 *
 * X/Y/Z 합성 진동 크기
 *
 *              ↓
 *
 * Sample Window
 *
 *              ↓
 *
 * Mean / RMS / Peak
 *
 *              ↓
 *
 * 대표 진동값 = RMS
 *
 *
 * ※ NORMAL / WARNING / DANGER 판정은
 *    vibration_state.c에서 처리한다.
 * ============================================================
 */


/*
 * ============================================================
 * Window Size
 * ============================================================
 *
 * 현재 Application Sampling 주기 = 800ms (약 1.25Hz)
 *
 * 현재 Application의 800ms Sampling에서 4 Sample을 사용하면
 *
 * 4 * 0.8초
 *
 * ≈ 3.2초
 *
 * 즉 약 3.2초 구간의 진동 데이터를 이용하여
 * RMS / Peak를 계산한다.
 *
 * 너무 짧으면 순간 노이즈 영향을 많이 받고,
 * 너무 길면 상태 변화 반응이 느려진다.
 *
 * 현재 4 Sample은 상태 전이 테스트용 값이며
 * 실제 회전체 측정 후 변경할 수 있다.
 */
#define VIBRATION_WINDOW_SIZE            4U


/*
 * ============================================================
 * Base Filter
 * ============================================================
 *
 * 중력 + 설치 방향 + 센서의 정적인 Offset을
 * 천천히 따라가는 기준값을 만든다.
 *
 * 값이 1.0에 가까울수록
 * 기준값이 천천히 변한다.
 *
 * 현재 0.95 사용.
 *
 * 빠른 진동은 기준값에 포함시키지 않고,
 * 천천히 변하는 중력 / 기울기 성분만 따라가도록 한다.
 */
#define VIBRATION_BASE_ALPHA             0.95f


/*
 * ============================================================
 * Noise Filter
 * ============================================================
 *
 * 기준값을 제거한 진동 데이터에
 * 간단한 1차 저역통과필터를 적용한다.
 *
 * 현재값을 70% 정도 반영하여
 * 순간적인 센서 Noise를 완화한다.
 *
 * MPU6050 내부 DLPF도 이미 적용되어 있으므로
 * 여기서는 강한 필터가 아니라 가벼운 추가 필터를 사용한다.
 */
#define VIBRATION_FILTER_ALPHA           0.70f


/*
 * ============================================================
 * 진동 결과 구조체
 * ============================================================
 */
typedef struct
{
    /*
     * --------------------------------------------------------
     * 기준 가속도
     * --------------------------------------------------------
     *
     * 설치 방향의 중력 성분 +
     * 센서의 정적인 Offset을 포함하는 기준값.
     *
     * 예:
     *
     * 현재 실제 센서 설치 상태가
     *
     * X ≈ +0.14g
     * Y ≈ +0.29g
     * Z ≈ -0.94g
     *
     * 라면 이 값들이 대략적인 기준값이 된다.
     */
    float base_x;
    float base_y;
    float base_z;


    /*
     * --------------------------------------------------------
     * 진동 축별 값
     * --------------------------------------------------------
     *
     * 기준값 제거 + Noise Filter가 적용된 결과.
     *
     * 단위 : g
     */
    float vibration_x;
    float vibration_y;
    float vibration_z;


    /*
     * --------------------------------------------------------
     * 순간 합성 진동 크기
     * --------------------------------------------------------
     *
     * sqrt(
     *     vibration_x^2 +
     *     vibration_y^2 +
     *     vibration_z^2
     * )
     *
     * 단위 : g
     */
    float vibration_magnitude;


    /*
     * --------------------------------------------------------
     * Window 평균 진동
     * --------------------------------------------------------
     *
     * Window 내 Sample의 진동 크기 평균.
     */
    float vibration_mean;


    /*
     * --------------------------------------------------------
     * RMS
     * --------------------------------------------------------
     *
     * Root Mean Square
     *
     * 진동의 전체적인 에너지 / 크기를 표현하는
     * 대표적인 특징값이다.
     *
     * 이번 프로젝트에서는 가장 중요한 진동값으로 사용한다.
     */
    float vibration_rms;


    /*
     * --------------------------------------------------------
     * Peak
     * --------------------------------------------------------
     *
     * Window 내 Sample 중 가장 큰 순간 진동값.
     *
     * 충격이나 순간적으로 큰 흔들림을 확인할 때 유용하다.
     */
    float vibration_peak;


    /*
     * --------------------------------------------------------
     * 대표 진동값
     * --------------------------------------------------------
     *
     * 관제 및 vibration_state.c에서 사용할 대표값.
     *
     * 현재는 RMS를 대표 진동값으로 사용한다.
     *
     * vibration_value = vibration_rms
     */
    float vibration_value;


    /*
     * --------------------------------------------------------
     * 정상 상태 RMS 기준값
     * --------------------------------------------------------
     *
     * 정상 회전 상태에서 측정한 RMS 값.
     *
     * 지금은 임의로 값을 넣지 않는다.
     *
     * 이후 sensor_calibration.c에서 실제 정상 회전체를
     * 측정한 뒤 vibration_set_normal_rms()로 전달한다.
     */
    float normal_rms;


    /*
     * --------------------------------------------------------
     * 정상 상태와 현재 RMS의 차이
     * --------------------------------------------------------
     *
     * rms_difference
     *
     * = 현재 RMS - 정상 RMS
     *
     * 예)
     *
     * 정상 RMS = 0.03g
     * 현재 RMS = 0.08g
     *
     * 차이 = +0.05g
     */
    float rms_difference;


    /*
     * 정상 기준값이 설정되어 있는지 확인.
     */
    bool normal_reference_set;


    /*
     * 현재 Window에 들어간 Sample 개수.
     *
     * 0 → 63까지 증가하다가
     * Window 계산 완료 후 다시 0부터 시작한다.
     */
    uint16_t sample_count;


    /*
     * RMS / Peak 결과가 몇 번 갱신되었는지 표시.
     *
     * Live Watch에서 이 값이 증가한다면
     * 진동 Window 계산이 정상적으로 반복되고 있다는 뜻이다.
     */
    uint32_t update_count;

} vibration_data_t;


/*
 * ============================================================
 * 초기화
 * ============================================================
 *
 * 모든 필터와 누적값을 초기화한다.
 */
void vibration_init(void);


/*
 * ============================================================
 * 진동 데이터 Update
 * ============================================================
 *
 * MPU6050에서 읽은 가속도 g 값을 전달한다.
 *
 * 약 8ms마다 한 번 호출한다.
 *
 * 반환값
 *
 * true
 * → Window Sample이 모여 새로운 RMS / Peak 결과가 만들어짐
 *
 * false
 * → 아직 Window를 수집 중
 */
bool vibration_update(float accel_x,
                      float accel_y,
                      float accel_z);


/*
 * 현재 진동 처리 결과를 전달한다.
 */
void vibration_get_data(vibration_data_t *data);


/*
 * 정상 상태 RMS 기준값 설정
 *
 * ※ 현재 단계에서 임의 값 사용 금지.
 *
 * 실제 정상 회전 상태를 측정한 뒤
 * sensor_calibration.c에서 사용할 함수이다.
 */
void vibration_set_normal_rms(float normal_rms);


/*
 * 정상 기준값을 삭제한다.
 */
void vibration_clear_normal_rms(void);


#endif
